import assert from 'node:assert/strict';
import { parseDecision, cleanSpeech, isPass } from '../src/agent.js';
const opts = [{ seat: 1, name: '老周' }, { seat: 3, name: '林姐' }, { seat: 12, name: '阿泽' }];
assert.deepEqual(parseDecision('我觉得他有问题\n投票：3号', '投票', opts), { seat: 3 });
assert.deepEqual(parseDecision('**投票：12号**', '投票', opts), { seat: 12 });
assert.deepEqual(parseDecision('投票: 林姐', '投票', opts), { seat: 3 });
assert.deepEqual(parseDecision('先不投了\n投票：弃票', '投票', opts), { none: true });
assert.deepEqual(parseDecision('杀：无', '杀', opts), { none: true });
assert.deepEqual(parseDecision('12', '查验', opts), { seat: 12 });
assert.deepEqual(parseDecision('1号和3号都可疑', '投票', opts), null);
assert.deepEqual(parseDecision('开枪：1号 老周', '开枪', opts), { seat: 1 });
assert.equal(cleanSpeech('老周：我是好人。<notes>盯3号</notes>', ['老周']), '我是好人。');
assert.equal(cleanSpeech('3号 老周：我是好人。', ['老周']), '我是好人。');
assert.equal(cleanSpeech('林姐：你先说。', ['老周']), '林姐：你先说。');
assert.equal(cleanSpeech('<think>hmm</think>“我没什么要说的。”'), '我没什么要说的。');
assert.equal(cleanSpeech('3号你别笑：说说看。'), '3号你别笑：说说看。');
assert.ok(isPass('过'));
assert.ok(isPass('过。'));
assert.ok(!isPass('过了今天再说吧，我觉得3号有问题'));
console.log('✓ 解析测试通过');
